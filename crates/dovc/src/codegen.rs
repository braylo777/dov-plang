//! C11 code generation. Input must have passed `check`.

use crate::ast::*;
use crate::check::Types;
use std::collections::HashSet;
use std::fmt::Write;

/// C type for `extern "C"` prototypes: i64 maps to C `long` (LP64 targets, checked
/// by a static assert in dov_rt.h), so declarations match libc exactly.
fn c_abi_ty(t: &Type) -> String {
    match t {
        Type::I64 => "long".into(),
        other => c_ty(other),
    }
}

fn c_ty(t: &Type) -> String {
    match t {
        Type::I64 => "int64_t".into(),
        Type::Bool => "bool".into(),
        Type::Str => "const char *".into(),
        Type::Unit => "void".into(),
        Type::Agent(a) => format!("dov_agent_{a} *"),
    }
}

/// Quote a string as a C literal. Non-printable and non-ASCII bytes become octal escapes.
pub fn c_str(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            0x20..=0x7e if b != b'?' => out.push(b as char),
            _ => {
                let _ = write!(out, "\\{b:03o}");
            }
        }
    }
    out.push('"');
    out
}

struct Gen<'a> {
    types: &'a Types,
    out: String,
    locals: Vec<HashSet<String>>,
    in_handler: bool,
    indent: usize,
    user_fns: HashSet<String>,
}

pub fn generate(prog: &Program, types: &Types) -> String {
    let user_fns = prog
        .items
        .iter()
        .filter_map(|i| {
            if let Item::Fn(f) = i {
                Some(f.name.clone())
            } else {
                None
            }
        })
        .collect();
    let mut g = Gen {
        types,
        out: String::new(),
        locals: Vec::new(),
        in_handler: false,
        indent: 0,
        user_fns,
    };
    g.program(prog);
    g.out
}

impl<'a> Gen<'a> {
    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn params(ps: &[Param], prefix: &str) -> String {
        let mut v: Vec<String> = Vec::new();
        if !prefix.is_empty() {
            v.push(prefix.to_string());
        }
        v.extend(ps.iter().map(|p| format!("{} v_{}", c_ty(&p.ty), p.name)));
        if v.is_empty() {
            "void".into()
        } else {
            v.join(", ")
        }
    }

    fn program(&mut self, prog: &Program) {
        self.line("/* generated by dovc 0.1 — .dov pLang */");
        self.line("#include \"dov_rt.h\"");
        self.line("");
        let agents: Vec<&AgentDecl> = prog
            .items
            .iter()
            .filter_map(|i| {
                if let Item::Agent(a) = i {
                    Some(a)
                } else {
                    None
                }
            })
            .collect();
        let fns: Vec<&FnDecl> = prog
            .items
            .iter()
            .filter_map(|i| if let Item::Fn(f) = i { Some(f) } else { None })
            .collect();

        for a in &agents {
            self.line(&format!(
                "typedef struct dov_agent_{0} dov_agent_{0};",
                a.name
            ));
        }
        for a in &agents {
            self.line(&format!("struct dov_agent_{} {{", a.name));
            if a.fields.is_empty() {
                self.line("    char dov_unused;");
            }
            for f in &a.fields {
                let t = &self.types[&f.init.pos];
                self.line(&format!("    {} f_{};", c_ty(t), f.name));
            }
            self.line("};");
        }
        for i in &prog.items {
            if let Item::Extern(e) = i {
                let ps: Vec<String> = e.params.iter().map(|p| c_abi_ty(&p.ty)).collect();
                let ps = if ps.is_empty() {
                    "void".into()
                } else {
                    ps.join(", ")
                };
                self.line(&format!("{} {}({});", c_abi_ty(&e.ret), e.name, ps));
            }
        }
        for f in &fns {
            self.line(&format!(
                "static {} dov_fn_{}({});",
                c_ty(&f.ret),
                f.name,
                Self::params(&f.params, "")
            ));
        }
        for a in &agents {
            self.line(&format!(
                "static dov_agent_{0} *dov_spawn_{0}(void);",
                a.name
            ));
            for h in &a.handlers {
                let selfp = format!("dov_agent_{} *self", a.name);
                self.line(&format!(
                    "static void dov_on_{}_{}({});",
                    a.name,
                    h.name,
                    Self::params(&h.params, &selfp)
                ));
            }
        }
        self.line("");

        // Message structs, trampolines and spawn functions.
        for a in &agents {
            for h in &a.handlers {
                let tag = format!("{}_{}", a.name, h.name);
                if !h.params.is_empty() {
                    self.line("typedef struct {");
                    for (i, p) in h.params.iter().enumerate() {
                        self.line(&format!("    {} a{};", c_ty(&p.ty), i));
                    }
                    self.line(&format!("}} dov_msg_{tag};"));
                }
                self.line(&format!(
                    "static void dov_tramp_{tag}(void *self, void *args) {{"
                ));
                if h.params.is_empty() {
                    self.line("    (void)args;");
                    self.line(&format!("    dov_on_{tag}((dov_agent_{} *)self);", a.name));
                } else {
                    self.line(&format!("    dov_msg_{tag} *m = (dov_msg_{tag} *)args;"));
                    let args: Vec<String> =
                        (0..h.params.len()).map(|i| format!("m->a{i}")).collect();
                    self.line(&format!(
                        "    dov_on_{tag}((dov_agent_{} *)self, {});",
                        a.name,
                        args.join(", ")
                    ));
                }
                self.line("}");
            }
            self.line(&format!(
                "static dov_agent_{0} *dov_spawn_{0}(void) {{",
                a.name
            ));
            self.line(&format!(
                "    dov_agent_{0} *self = (dov_agent_{0} *)dov_alloc(sizeof *self);",
                a.name
            ));
            self.locals = vec![HashSet::new()];
            self.in_handler = false;
            for f in &a.fields {
                let v = self.expr(&f.init);
                self.line(&format!("    self->f_{} = {};", f.name, v));
            }
            self.line("    return self;");
            self.line("}");
        }
        self.line("");

        for f in &fns {
            self.in_handler = false;
            self.locals = vec![f.params.iter().map(|p| p.name.clone()).collect()];
            self.line(&format!(
                "static {} dov_fn_{}({}) {{",
                c_ty(&f.ret),
                f.name,
                Self::params(&f.params, "")
            ));
            self.indent = 1;
            for p in &f.params {
                self.line(&format!("(void)v_{};", p.name));
            }
            self.stmts(&f.body);
            if f.ret != Type::Unit {
                self.line(&format!(
                    "dov_panic(\"missing return in `{}`\", {});",
                    f.name, f.pos.line
                ));
            }
            self.indent = 0;
            self.line("}");
        }
        for a in &agents {
            for h in &a.handlers {
                self.in_handler = true;
                self.locals = vec![h.params.iter().map(|p| p.name.clone()).collect()];
                let selfp = format!("dov_agent_{} *self", a.name);
                self.line(&format!(
                    "static void dov_on_{}_{}({}) {{",
                    a.name,
                    h.name,
                    Self::params(&h.params, &selfp)
                ));
                self.indent = 1;
                self.line("(void)self;");
                for p in &h.params {
                    self.line(&format!("(void)v_{};", p.name));
                }
                self.stmts(&h.body);
                self.indent = 0;
                self.line("}");
            }
        }
        self.line("");
        self.line("int main(void) {");
        self.line("    dov_fn_main();");
        self.line("    dov_run();");
        self.line("    return 0;");
        self.line("}");
    }

    fn stmts(&mut self, b: &Block) {
        for s in b {
            self.stmt(s);
        }
    }

    fn block(&mut self, b: &Block) {
        self.locals.push(HashSet::new());
        self.indent += 1;
        self.stmts(b);
        self.indent -= 1;
        self.locals.pop();
    }

    fn stmt(&mut self, s: &Stmt) {
        match &s.kind {
            StmtKind::Let {
                name,
                mutable,
                init,
                ..
            } => {
                let t = c_ty(&self.types[&init.pos]);
                let v = self.expr(init);
                // `let` becomes a C const (pointer types: const pointer).
                let decl = match (*mutable, t.ends_with('*')) {
                    (true, _) => format!("{t} v_{name}"),
                    (false, true) => format!("{t}const v_{name}"),
                    (false, false) => format!("const {t} v_{name}"),
                };
                self.line(&format!("{decl} = {v};"));
                self.locals.last_mut().unwrap().insert(name.clone());
            }
            StmtKind::Assign { name, value } => {
                let target = self.var(name);
                let v = self.expr(value);
                self.line(&format!("{target} = {v};"));
            }
            StmtKind::If { cond, then, els } => {
                let c = Self::cond(self.expr(cond));
                self.line(&format!("if ({c}) {{"));
                self.block(then);
                if let Some(e) = els {
                    self.line("} else {");
                    self.block(e);
                }
                self.line("}");
            }
            StmtKind::While { cond, body } => {
                let c = Self::cond(self.expr(cond));
                self.line(&format!("while ({c}) {{"));
                self.block(body);
                self.line("}");
            }
            StmtKind::Return(None) => self.line("return;"),
            StmtKind::Return(Some(e)) => {
                let v = self.expr(e);
                self.line(&format!("return {v};"));
            }
            StmtKind::Expr(e) => {
                let v = self.expr(e);
                self.line(&format!("(void)({v});"));
            }
            StmtKind::Send {
                target,
                handler,
                args,
            } => {
                let Type::Agent(a) = &self.types[&target.pos] else {
                    unreachable!("checked")
                };
                let tag = format!("{a}_{handler}");
                let t = self.expr(target);
                self.line("{");
                if args.is_empty() {
                    self.line(&format!("    dov_send({t}, dov_tramp_{tag}, NULL);"));
                } else {
                    self.line(&format!(
                        "    dov_msg_{tag} *m = (dov_msg_{tag} *)dov_alloc(sizeof *m);"
                    ));
                    for (i, arg) in args.iter().enumerate() {
                        let v = self.expr(arg);
                        self.line(&format!("    m->a{i} = {v};"));
                    }
                    self.line(&format!("    dov_send({t}, dov_tramp_{tag}, m);"));
                }
                self.line("}");
            }
        }
    }

    /// Drop one redundant outer paren pair so clang's -Wparentheses-equality stays quiet.
    fn cond(c: String) -> String {
        if c.starts_with('(') && c.ends_with(')') {
            let inner = &c[1..c.len() - 1];
            let mut depth = 0i32;
            let balanced = inner.chars().all(|ch| {
                match ch {
                    '(' => depth += 1,
                    ')' => depth -= 1,
                    _ => {}
                }
                depth >= 0
            });
            if balanced && depth == 0 && !inner.contains('"') {
                return inner.to_string();
            }
        }
        c
    }

    fn var(&self, name: &str) -> String {
        let local = self.locals.iter().any(|s| s.contains(name));
        if !local && self.in_handler {
            format!("self->f_{name}")
        } else {
            format!("v_{name}")
        }
    }

    fn expr(&mut self, e: &Expr) -> String {
        match &e.kind {
            ExprKind::Int(v) => format!("INT64_C({v})"),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Str(s) => c_str(s),
            ExprKind::Var(n) => self.var(n),
            ExprKind::Unary(UnOp::Neg, x) => format!("dov_neg({}, {})", self.expr(x), e.pos.line),
            ExprKind::Unary(UnOp::Not, x) => format!("(!{})", self.expr(x)),
            ExprKind::Binary(op, l, r) => {
                let (a, b) = (self.expr(l), self.expr(r));
                let line = e.pos.line;
                match op {
                    BinOp::Add => format!("dov_add({a}, {b}, {line})"),
                    BinOp::Sub => format!("dov_sub({a}, {b}, {line})"),
                    BinOp::Mul => format!("dov_mul({a}, {b}, {line})"),
                    BinOp::Div => format!("dov_div({a}, {b}, {line})"),
                    BinOp::Rem => format!("dov_rem({a}, {b}, {line})"),
                    BinOp::Eq | BinOp::Ne => {
                        let neg = if *op == BinOp::Ne { "!" } else { "" };
                        if self.types[&l.pos] == Type::Str {
                            format!("({neg}dov_str_eq({a}, {b}))")
                        } else {
                            format!("({a} {}= {b})", if neg.is_empty() { "=" } else { "!" })
                        }
                    }
                    BinOp::Lt => format!("({a} < {b})"),
                    BinOp::Le => format!("({a} <= {b})"),
                    BinOp::Gt => format!("({a} > {b})"),
                    BinOp::Ge => format!("({a} >= {b})"),
                    BinOp::And => format!("({a} && {b})"),
                    BinOp::Or => format!("({a} || {b})"),
                }
            }
            ExprKind::Call(name, args) if name == "print" => {
                let mut parts = Vec::new();
                for a in args {
                    let v = self.expr(a);
                    parts.push(match self.types[&a.pos] {
                        Type::I64 => format!("dov_print_i64({v})"),
                        Type::Bool => format!("dov_print_bool({v})"),
                        _ => format!("dov_print_str({v})"),
                    });
                }
                parts.push("dov_print_nl()".into());
                format!("({})", parts.join(", "))
            }
            ExprKind::Call(name, args) => {
                let vs: Vec<String> = args.iter().map(|a| self.expr(a)).collect();
                let is_extern = !self.is_dov_fn(name);
                let callee = if is_extern {
                    name.clone()
                } else {
                    format!("dov_fn_{name}")
                };
                format!("{callee}({})", vs.join(", "))
            }
            ExprKind::Spawn(a) => format!("dov_spawn_{a}()"),
        }
    }

    fn is_dov_fn(&self, name: &str) -> bool {
        self.user_fns.contains(name)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn c_string_escapes() {
        assert_eq!(c_str("a\"b\\c\n"), r#""a\"b\\c\n""#);
        assert_eq!(c_str("é"), r#""\303\251""#);
        assert_eq!(c_str("??="), r#""\077\077=""#);
    }
}
