#!/usr/bin/env python3
"""Build the static playground in playground/ (no npm).

1. `cargo build -p dovc-wasm --release --target wasm32-unknown-unknown` -> playground/dovc.wasm
2. playground/presets/*.dov + their output from a native `dovc run` -> playground/presets.js
Deploy: `wrangler pages deploy playground --project-name dov-playground`.
"""
import json, os, pathlib, shutil, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
PG = ROOT / "playground"
TARGET = pathlib.Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target"))


def main():
    subprocess.run(["cargo", "build", "-p", "dovc-wasm", "--release", "--target", "wasm32-unknown-unknown"],
                   cwd=ROOT, check=True)
    subprocess.run(["cargo", "build", "-p", "dovc", "--release"], cwd=ROOT, check=True)
    shutil.copy(TARGET / "wasm32-unknown-unknown" / "release" / "dovc_wasm.wasm", PG / "dovc.wasm")
    dovc = TARGET / "release" / "dovc"
    presets = []
    for f in sorted((PG / "presets").glob("*.dov")):
        if f.name.startswith("._"):
            continue
        r = subprocess.run([str(dovc), "run", str(f)], capture_output=True, text=True)
        title = f.stem.split("_", 1)[1].replace("_", " ")
        presets.append({"title": title, "source": f.read_text(),
                        "output": r.stdout if r.returncode == 0 else ""})
    (PG / "presets.js").write_text("// generated by scripts/build_playground.py\nconst PRESETS = "
                                   + json.dumps(presets, indent=1) + ";\n")
    print(f"playground: {len(presets)} presets, dovc.wasm {(PG / 'dovc.wasm').stat().st_size} bytes")


if __name__ == "__main__":
    main()
